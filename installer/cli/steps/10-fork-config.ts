import {writeFileSync} from "node:fs";
import {resolve} from "node:path";
import {run} from "../lib/exec.ts";
import type {Step} from "../lib/types.ts";

/**
 * Write skeleton fork.config.ts and the Flutter mirror. Most values are
 * placeholders the operator fills in via /admin/install. Only the values we
 * already know from CLI inputs (practice name, super-admin, agent names,
 * portal URL) get real values up front.
 */
export const forkConfigStep: Step = {
  id: "10-fork-config",
  title: "Write fork.config.ts skeleton",
  idempotent: true,
  async run({state, log}) {
    const {targetDir, projectId, practiceName, practiceShortName, superAdminEmail, portalDomain, adminAgentName, patientAgentName} =
      state.inputs;
    const apphostingUrl = state.artifacts.apphostingUrl;
    if (!targetDir || !projectId || !practiceName || !practiceShortName || !superAdminEmail || !adminAgentName || !patientAgentName) {
      throw new Error("inputs missing");
    }

    const portal = portalDomain ?? apphostingUrl?.replace(/^https?:\/\//, "") ?? `${projectId}.web.app`;
    const portalUrl = `https://${portal}`;

    const config = renderForkConfig({
      practiceName,
      practiceShortName,
      superAdminEmail,
      portalDomain: portal,
      portalUrl,
      adminAgentName,
      patientAgentName,
    });

    const target = resolve(targetDir, "fork.config.ts");
    writeFileSync(target, config);
    log.success(`Wrote skeleton ${target}`);

    // Mirror into mobile/lib/config/branding.dart — minimal subset.
    const dartPath = resolve(targetDir, "mobile", "lib", "config", "branding.dart");
    writeFileSync(dartPath, renderDartBranding({practiceName, practiceShortName, portalUrl}));
    log.success(`Wrote ${dartPath}`);

    // Also keep functions/src/_fork.config.ts in sync (the prebuild script
    // re-copies on `npm run build`, but we seed it now so deploy-first doesn't
    // need a separate prebuild round-trip).
    try {
      run("bash", [resolve(targetDir, "scripts", "sync-fork-config.sh")], {cwd: targetDir, capture: true});
      log.info("Synced fork.config.ts → functions/src/_fork.config.ts");
    } catch (err) {
      log.warn(`scripts/sync-fork-config.sh failed (will retry on functions build): ${(err as Error).message.split("\n")[0]}`);
    }
  },
};


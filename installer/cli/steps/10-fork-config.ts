function renderDartBranding(v: {practiceName: string; practiceShortName: string; portalUrl: string}): string {
  return `// Generated by patient-installer. Mirror of /fork.config.ts (subset).
//
// Flutter cannot import TS so this file is regenerated by the installer
// AND can be re-emitted from /admin/install on the deployed portal.

class Branding {
  static const String appName = ${dart(v.practiceShortName)};
  static const String practiceName = ${dart(v.practiceName)};
  static const String shortName = ${dart(v.practiceShortName)};
  static const String portalUrl = ${dart(v.portalUrl)};
  static const String supportEmail = ${dart("support@" + v.portalUrl.replace(/^https?:\/\//, ""))};
}
`;
}

